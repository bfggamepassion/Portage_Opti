def glyph_bytes(ch):
    rows = FONT.get(ch, FONT[' '])
    out = [0]
    for r in rows:
        v = 0
        for i, c in enumerate(r):           # pixels CPC 1-3 -> bits Coleco 5-0
            if c == '#':
                v |= 3 << (4 - 2 * i)
        out.append(v)
    return bytes(out)
